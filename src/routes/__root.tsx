function RootShell({ children }: { children: ReactNode }) {
  return (
    <html lang="pt-BR">
      <head>
        <HeadContent />
      </head>
      <body>
        {children}
        <Scripts />
      </body>
    </html>
  );
}

function RootComponent() {
  const { queryClient } = Route.useRouteContext();
  const router = useRouter();
  const pathname = useRouterState({ select: (state) => state.location.pathname });
  const usaGuia = pathname.startsWith("/app") || pathname.startsWith("/barbeiro") || pathname.startsWith("/admin");

  useEffect(() => {
    let ativo = true;
    let cancelar: (() => void) | undefined;
    void import("@/integrations/supabase/client").then(({ supabase }) => {
      if (!ativo) return;
      const { data } = supabase.auth.onAuthStateChange((event) => {
        if (event !== "SIGNED_IN" && event !== "SIGNED_OUT" && event !== "USER_UPDATED") return;
        // A sessão é cacheada pelas guardas: precisa cair junto com a troca de conta.
        queryClient.removeQueries({ queryKey: ["sessao"] });
        router.invalidate();
        if (event !== "SIGNED_OUT") queryClient.invalidateQueries({ type: "active" });
      });
      cancelar = () => data.subscription.unsubscribe();
    });
    return () => {
      ativo = false;
      cancelar?.();
    };
  }, [router, queryClient]);

  return (
    <QueryClientProvider client={queryClient}>
      {/* Required: nested routes render here. Removing <Outlet /> breaks all child routes. */}
      <GlobalDesign>
        {usaGuia ? <Suspense fallback={<Outlet />}><GuiaProvider><Outlet /></GuiaProvider></Suspense> : <Outlet />}
      </GlobalDesign>
    </QueryClientProvider>
  );
}
