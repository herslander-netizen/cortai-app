CREATE OR REPLACE FUNCTION public.preparar_comanda(_agendamento_id uuid) RETURNS uuid LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE a public.agendamentos%ROWTYPE; s public.servicos%ROWTYPE; cfg public.configuracoes_financeiras%ROWTYPE; cid uuid;
BEGIN
 SELECT * INTO a FROM public.agendamentos WHERE id=_agendamento_id FOR UPDATE;
 IF a.id IS NULL OR NOT public.has_tenant_permission(a.tenant_id,'confirmar_pagamento') THEN RAISE EXCEPTION 'sem permissao'; END IF;
 IF a.status IN ('cancelado','falta') THEN RAISE EXCEPTION 'agendamento nao pode ser atendido'; END IF;
 SELECT id INTO cid FROM public.comandas WHERE agendamento_id=a.id;
 IF cid IS NOT NULL THEN RETURN cid; END IF;
 INSERT INTO public.configuracoes_financeiras(tenant_id) VALUES(a.tenant_id) ON CONFLICT DO NOTHING;
 SELECT * INTO cfg FROM public.configuracoes_financeiras WHERE tenant_id=a.tenant_id;
 INSERT INTO public.comandas(tenant_id,cliente_id,profissional_id,agendamento_id,status,aberta_por) VALUES(a.tenant_id,a.cliente_id,a.profissional_id,a.id,'em_atendimento',auth.uid()) RETURNING id INTO cid;
 IF a.servico_id IS NOT NULL THEN
   SELECT * INTO s FROM public.servicos WHERE id=a.servico_id AND tenant_id=a.tenant_id;
   INSERT INTO public.comanda_itens(comanda_id,tipo,servico_id,descricao,quantidade,valor_unitario_centavos,valor_total_centavos,comissao_percentual,comissao_centavos)
   VALUES(cid,'servico',s.id,s.nome,1,a.valor_centavos,a.valor_centavos,COALESCE(s.comissao_percentual,cfg.comissao_servico_percentual),round(a.valor_centavos*COALESCE(s.comissao_percentual,cfg.comissao_servico_percentual)/100.0));
 END IF;
 UPDATE public.agendamentos SET status='confirmado' WHERE id=a.id AND status='pendente';
 RETURN cid;
END $$;
REVOKE ALL ON FUNCTION public.preparar_comanda(uuid) FROM PUBLIC, anon;
